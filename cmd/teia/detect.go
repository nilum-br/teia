type multiFlag []string

func (m *multiFlag) String() string     { return strings.Join(*m, ",") }
func (m *multiFlag) Set(v string) error { *m = append(*m, v); return nil }

// detect probes what a platform already runs and prints a starting config.
func detect(args []string) error {
	fs := flag.NewFlagSet("detect", flag.ExitOnError)
	var proms, tempos, lokis multiFlag
	fs.Var(&proms, "prometheus", "Prometheus-compatible URL (repeatable)")
	fs.Var(&tempos, "tempo", "Tempo URL (repeatable)")
	fs.Var(&lokis, "loki", "Loki URL (repeatable)")
	kube := fs.Bool("kubernetes", false, "probe the current Kubernetes context (or in-cluster config)")
	dock := fs.Bool("docker", false, "probe the local Docker engine (DOCKER_HOST or the OS default)")
	_ = fs.Parse(args)
	if len(proms)+len(tempos)+len(lokis) == 0 && !*kube && !*dock {
		return fmt.Errorf("nothing to probe: pass --prometheus, --tempo, --loki, --kubernetes and/or --docker")
	}

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	out := os.Stdout
	var yaml strings.Builder
	yaml.WriteString("# generated by teia detect\ninterval: 30s\nsources:\n  declared:\n    paths: [./flows]\n")

	if len(proms) > 0 {
		yaml.WriteString("  prometheus:\n")
	}
	for _, u := range proms {
		fmt.Fprintf(out, "Prometheus %s\n", u)
		src := prometheus.New("prometheus", prometheus.Config{URL: u})
		found, err := src.Detect(ctx)
		if err != nil {
			fmt.Fprintf(out, "  x %v\n\n", err)
			continue
		}
		have := map[string]bool{}
		for _, p := range found {
			have[p.Name] = true
		}
		for _, p := range prometheus.Presets {
			mark := "  -"
			if have[p.Name] {
				mark = "  ok"
			}
			fmt.Fprintf(out, "%-4s %-14s %s\n", mark, p.Name, p.Description)
		}
		if obs, err := src.Discover(ctx); err == nil {
			fmt.Fprintf(out, "       %d edges in the last 5m; %s\n", len(obs.Edges), obs.Message)
		}
		fmt.Fprintln(out)
		fmt.Fprintf(&yaml, "    - url: %s\n      presets: [auto]\n", u)
	}

	if len(tempos) > 0 {
		yaml.WriteString("  tempo:\n")
	}
	for _, u := range tempos {
		fmt.Fprintf(out, "Tempo %s\n", u)
		obs, err := tempo.New("tempo", tempo.Config{URL: u, TracesPerService: 5, MaxTraces: 50}).Discover(ctx)
		report(out, obs, err)
		fmt.Fprintf(&yaml, "    - url: %s\n", u)
	}

	if len(lokis) > 0 {
		yaml.WriteString("  queries:\n")
	}
	for i, u := range lokis {
		fmt.Fprintf(out, "Loki %s\n", u)
		labels, err := lokiLabels(ctx, u)
		if err != nil {
			fmt.Fprintf(out, "  x %v\n\n", err)
			continue
		}
		fmt.Fprintf(out, "  ok stream labels: %s\n", strings.Join(labels, ", "))
		fmt.Fprintf(out, "     teia cannot guess your log format: edit the access-log query below.\n\n")
		fmt.Fprintf(&yaml, `    - name: access-logs-%d
      dialect: loki
      url: %s
      # one series per (callee, caller address); adapt the selector and parser to your logs
      query: sum by (service, remote_addr) (rate({service=~".+"} | json | __error__="" [$window]))
      from: remote_addr
      fromAddress: true
      to: service
      protocol: http
`, i+1, u)
	}

	if *kube {
		fmt.Fprintln(out, "Kubernetes")
		obs, err := kubernetes.New("kubernetes", kubernetes.Config{}).Discover(ctx)
		report(out, obs, err)
		yaml.WriteString("  kubernetes: {}\n")
	}
	if *dock {
		fmt.Fprintln(out, "Docker")
		obs, err := docker.New("docker", docker.Config{}).Discover(ctx)
		report(out, obs, err)
		yaml.WriteString("  docker: {}\n")
	}

	fmt.Fprintln(out, "Suggested teia.yaml (databases are explored with sources.postgres; see docs/sources.md):")
	fmt.Fprintln(out, "---")
	fmt.Fprint(out, yaml.String())
	return nil
}

func report(out io.Writer, obs source.Observation, err error) {
	switch {
	case err != nil:
		fmt.Fprintf(out, "  x %v\n\n", err)
		return
	case obs.Degraded:
		fmt.Fprintf(out, "  !  %s\n", obs.Message)
	default:
		fmt.Fprintf(out, "  ok %s (%d nodes, %d edges)\n", obs.Message, len(obs.Nodes), len(obs.Edges))
	}
	for _, f := range obs.Findings {
		fmt.Fprintf(out, "     %s: %s\n", severityLabel(f.Severity), f.Title)
	}
	fmt.Fprintln(out)
}

func severityLabel(s model.Severity) string { return string(s) }

func lokiLabels(ctx context.Context, base string) ([]string, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, strings.TrimRight(base, "/")+"/loki/api/v1/labels", nil)
	if err != nil {
		return nil, err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("HTTP %d", resp.StatusCode)
	}
	var body struct {
		Data []string `json:"data"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&body); err != nil {
		return nil, err
	}
	return body.Data, nil
}
